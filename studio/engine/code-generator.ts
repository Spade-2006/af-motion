/**
 * AF Motion Studio — Code Generation & Export Engine
 *
 * Produces clean, production-ready React component code, CSS custom properties,
 * and JSON configurations using official AF Motion subpath exports.
 */

import type {
  StudioAnimationConfig,
  StudioBackgroundConfig,
  StudioExportBundle,
} from "../types/index.js";

export function generateReactComponentCode(
  anim: StudioAnimationConfig,
  bg: StudioBackgroundConfig
): string {
  const isReducedMotionHandled = anim.reducedMotion;
  const isBackgroundEffect = bg.type === "aurora" || bg.type === "particles";

  const reactImports = new Set<string>(["useMotionAccessibility"]);
  if (anim.preset === "fadeUp" || anim.preset === "slideRight") {
    reactImports.add("Reveal");
  } else {
    reactImports.add("Interactive");
  }

  const coreImports = new Set<string>();
  if (bg.type === "aurora") coreImports.add("aurora");
  if (bg.type === "particles") coreImports.add("particleField");

  const importLines: string[] = [];
  if (coreImports.size > 0) {
    importLines.push(`import { ${Array.from(coreImports).join(", ")} } from "af-motion";`);
  }
  importLines.push(`import { ${Array.from(reactImports).join(", ")} } from "af-motion/react";`);

  return `"use client";

import React, { useEffect, useRef } from "react";
${importLines.join("\n")}

/**
 * Generated by AF Motion Studio
 * Preset: ${anim.preset ?? "Custom"} | Background: ${bg.type} (${bg.paletteName})
 */
export default function StudioExportedExperience() {
  const { prefersReducedMotion } = useMotionAccessibility();
  const canvasRef = useRef<HTMLCanvasElement | null>(null);

  ${
    isBackgroundEffect
      ? `useEffect(() => {
    if (!canvasRef.current || prefersReducedMotion) return;
    const cleanup = ${bg.type === "aurora" ? "aurora" : "particleField"}(canvasRef.current, {
      speed: ${bg.speed},
      density: ${bg.density},
    });
    return () => cleanup?.destroy?.();
  }, [prefersReducedMotion]);`
      : `// Background rendered via CSS gradient/patterns`
  }

  return (
    <div
      className="relative min-h-[480px] w-full flex items-center justify-center p-8 overflow-hidden rounded-2xl"
      style={{
        background: "${bg.colors.background}",
      }}
    >
      ${
        isBackgroundEffect
          ? `<canvas ref={canvasRef} className="absolute inset-0 pointer-events-none w-full h-full" />`
          : `<div
        className="absolute inset-0 pointer-events-none"
        style={{
          background: "${bg.type === "gradient" ? `linear-gradient(${bg.angle}deg, ${bg.colors.background}, ${bg.colors.primary}, ${bg.colors.secondary})` : bg.colors.background}",
        }}
      />`
      }

      <div
        className="relative z-10 px-8 py-6 rounded-xl shadow-2xl flex flex-col items-center gap-3"
        style={{
          backgroundColor: "${anim.properties.backgroundColor || "rgba(255, 255, 255, 0.08)"}",
          borderRadius: "${anim.properties.borderRadius}px",
          backdropFilter: "blur(16px)",
          transform: prefersReducedMotion ? "none" : "${anim.properties.scale !== 1 ? `scale(${anim.properties.scale})` : "none"}",
          transition: "transform ${anim.duration}ms ${anim.easing}",
        }}
      >
        <span className="text-xl font-bold tracking-tight text-white">
          AF Motion Studio Element
        </span>
        <p className="text-sm opacity-80 text-gray-300">
          Duration: ${anim.duration}ms | Easing: ${anim.easing}
        </p>
      </div>
    </div>
  );
}
`;
}

export function generateCSSVariables(
  anim: StudioAnimationConfig,
  bg: StudioBackgroundConfig
): Record<string, string> {
  return {
    "--af-studio-duration": `${anim.duration}ms`,
    "--af-studio-delay": `${anim.delay}ms`,
    "--af-studio-easing": anim.easing,
    "--af-studio-target-x": `${anim.properties.x}px`,
    "--af-studio-target-y": `${anim.properties.y}px`,
    "--af-studio-target-scale": String(anim.properties.scale),
    "--af-studio-target-rotate": `${anim.properties.rotate}deg`,
    "--af-studio-target-opacity": String(anim.properties.opacity),
    "--af-studio-target-radius": `${anim.properties.borderRadius}px`,
    "--af-studio-bg-primary": bg.colors.primary,
    "--af-studio-bg-secondary": bg.colors.secondary,
    "--af-studio-bg-accent": bg.colors.accent,
    "--af-studio-bg-base": bg.colors.background,
    "--af-studio-bg-angle": `${bg.angle}deg`,
  };
}

export function generateExportBundle(
  anim: StudioAnimationConfig,
  bg: StudioBackgroundConfig
): StudioExportBundle {
  const reactCode = generateReactComponentCode(anim, bg);
  const cssVariables = generateCSSVariables(anim, bg);
  const configJson = JSON.stringify(
    {
      version: "1.0.0",
      generator: "AF Motion Studio",
      animation: anim,
      background: bg,
    },
    null,
    2
  );

  const imports = [
    {
      subpath: "af-motion/react",
      namedImports: ["useMotionAccessibility", "Reveal", "Interactive"],
    },
  ];
  if (bg.type === "aurora" || bg.type === "particles") {
    imports.unshift({
      subpath: "af-motion",
      namedImports: [bg.type === "aurora" ? "aurora" : "particleField"],
    });
  }

  return {
    title: `AF Motion Studio — ${anim.preset ?? "Custom Animation"}`,
    reactCode,
    configJson,
    cssVariables,
    imports,
  };
}
